test('replanejar após apontamento preserva consumos, lotes e produção e bloqueia OP concluída',()=>{
 const h=sample(2)
 h.run('issueSheet',{id:h.op.id});h.run('startOp',{id:h.op.id})
 const report=()=>h.run('reportProduction',{id:h.op.id,quantidade:1,perdasKg:0,sobrasKg:0,validade:D.day(180),consumos:D.suggestConsumption(h.s,h.op,1)})
 report()
 const stock=JSON.stringify(h.s.lotes),records=JSON.stringify(h.op.apontamentos),formula=JSON.stringify(h.op.formula)
 h.run('modifyBatches',{id:h.op.id,maximoKg:1,quantidadeBatidas:2})
 assert.equal(h.op.quantidadeProduzida,1)
 assert.equal(JSON.stringify(h.s.lotes),stock)
 assert.equal(JSON.stringify(h.op.apontamentos),records)
 assert.equal(JSON.stringify(h.op.formula),formula)
 assert.equal(h.op.documentoOp.batidas.kgPorBatida,1)
 report()
 assert.throws(()=>h.run('modifyBatches',{id:h.op.id,maximoKg:1,quantidadeBatidas:2}),/OP aberta/)
})
